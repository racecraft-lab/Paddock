#!/usr/bin/env node

import { access, readdir, readFile } from 'node:fs/promises'
import path from 'node:path'

function parseList(value) {
  return value
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean)
}

function parseCounts(value) {
  return parseList(value)
    .map((entry) => {
      const [tag, rawCount] = entry.split(':')
      return { tag: tag?.trim(), count: Number.parseInt(rawCount, 10) }
    })
    .filter((entry) => entry.tag && Number.isFinite(entry.count) && entry.count > 0)
}

function parseArgs(argv) {
  const args = {
    mode: process.env.ARGOS_METADATA_MODE || null,
    root: null,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--mode') {
      args.mode = argv[index + 1]
      index += 1
    } else if (arg === '--root') {
      args.root = path.resolve(argv[index + 1])
      index += 1
    } else if (!args.mode && ['playwright', 'storybook'].includes(arg)) {
      args.mode = arg
    } else if (!args.root) {
      args.root = path.resolve(arg)
    } else {
      throw new Error(`Unknown argument: ${arg}`)
    }
  }

  if (!['playwright', 'storybook'].includes(args.mode)) {
    throw new Error('--mode must be either playwright or storybook')
  }

  return args
}

async function pathExists(filePath) {
  try {
    await access(filePath)
    return true
  } catch {
    return false
  }
}

async function collectMetadataFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...await collectMetadataFiles(entryPath))
      continue
    }
    if (entry.isFile() && entry.name.endsWith('.png.argos.json')) {
      files.push(entryPath)
    }
  }

  return files
}

function getPlaywrightConfig(rootOverride) {
  return {
    label: 'argos-playwright-metadata',
    root: rootOverride || path.join(process.cwd(), 'test-results'),
    expectedMetadata: Number.parseInt(process.env.ARGOS_PLAYWRIGHT_EXPECTED_METADATA || '19', 10),
    expectedTests: Number.parseInt(process.env.ARGOS_PLAYWRIGHT_EXPECTED_TESTS || '11', 10),
    allowedTestTags: parseList(process.env.ARGOS_PLAYWRIGHT_ALLOWED_TEST_TAGS || '@product-line-switcher,@feature-flag-admin,@ready-for-owner,@spec-007'),
    allowedScreenshotTags: parseList(process.env.ARGOS_PLAYWRIGHT_ALLOWED_SCREENSHOT_TAGS || 'product-line-switcher,feature-flag-admin,ready-for-owner,spec-007'),
    requiredDomainCounts: parseCounts(process.env.ARGOS_PLAYWRIGHT_REQUIRED_DOMAIN_COUNTS || 'product-line-switcher:9,feature-flag-admin:2,ready-for-owner:3,spec-007:5'),
  }
}

function getStorybookConfig(rootOverride) {
  return {
    label: 'argos-storybook-metadata',
    root: rootOverride || process.env.ARGOS_STORYBOOK_SCREENSHOT_DIR || path.join(process.cwd(), 'screenshots', 'storybook'),
    expectedMetadata: Number.parseInt(process.env.ARGOS_STORYBOOK_EXPECTED_METADATA || '28', 10),
    expectedStories: Number.parseInt(process.env.ARGOS_STORYBOOK_EXPECTED_STORIES || '18', 10),
    requiredStoryTags: parseList(process.env.ARGOS_STORYBOOK_REQUIRED_TAGS || 'visual'),
    requiredDomainStoryCounts: parseCounts(process.env.ARGOS_STORYBOOK_REQUIRED_DOMAIN_STORY_COUNTS || 'product-line-switcher:8,feature-flag-admin:2,task-pipeline-workflows:2,ready-for-owner:3,spec-007:3'),
  }
}

function validatePlaywrightMetadata(metadata, filePath, config) {
  const failures = []
  const test = metadata.test

  if (!test || typeof test !== 'object') {
    failures.push('missing test metadata')
    return failures
  }
  if (typeof test.title !== 'string' || test.title.length === 0) {
    failures.push('missing test.title')
  }
  if (!Array.isArray(test.titlePath) || test.titlePath.length === 0) {
    failures.push('missing test.titlePath')
  }
  if (typeof test.location?.file !== 'string' || test.location.file.length === 0) {
    failures.push('missing test.location.file')
  }
  if (
    config.allowedTestTags.length > 0 &&
    (!Array.isArray(test.tags) || !config.allowedTestTags.some((tag) => test.tags.includes(tag)))
  ) {
    failures.push(`missing one of Playwright test tags: ${config.allowedTestTags.join(', ')}`)
  }
  if (
    config.allowedScreenshotTags.length > 0 &&
    (!Array.isArray(metadata.tags) || !config.allowedScreenshotTags.some((tag) => metadata.tags.includes(tag)))
  ) {
    failures.push(`missing one of screenshot tags: ${config.allowedScreenshotTags.join(', ')}`)
  }
  if (metadata.sdk?.name !== '@argos-ci/playwright') {
    failures.push('metadata was not generated by @argos-ci/playwright')
  }
  if (metadata.automationLibrary?.name !== '@playwright/test') {
    failures.push('metadata was not generated from @playwright/test')
  }

  return failures.map((failure) => `${path.relative(process.cwd(), filePath)}: ${failure}`)
}

function validateStorybookMetadata(metadata, filePath, config) {
  const failures = []

  if (metadata.sdk?.name !== '@argos-ci/storybook') {
    failures.push('metadata was not generated by @argos-ci/storybook')
  }
  if (metadata.automationLibrary?.name !== '@storybook/addon-vitest') {
    failures.push('metadata was not generated from @storybook/addon-vitest')
  }
  if (typeof metadata.story?.id !== 'string') {
    failures.push('missing Storybook story id')
  }
  for (const tag of config.requiredStoryTags) {
    if (!Array.isArray(metadata.story?.tags) || !metadata.story.tags.includes(tag)) {
      failures.push(`missing Storybook story tag ${tag}`)
    }
  }

  return failures.map((failure) => `${path.relative(process.cwd(), filePath)}: ${failure}`)
}

async function readMetadata(filePath, failures) {
  try {
    return JSON.parse(await readFile(filePath, 'utf8'))
  } catch (error) {
    failures.push(`${path.relative(process.cwd(), filePath)}: invalid JSON (${error.message})`)
    return null
  }
}

async function verifyCompanionScreenshot(filePath, failures) {
  const screenshotPath = filePath.slice(0, -'.argos.json'.length)
  if (!await pathExists(screenshotPath)) {
    failures.push(`${path.relative(process.cwd(), filePath)}: missing companion screenshot`)
  }
}

async function verifyPlaywright(config) {
  const metadataFiles = await collectMetadataFiles(config.root)
  const failures = []
  const uniqueTests = new Set()
  const domainCounts = new Map()

  for (const filePath of metadataFiles) {
    await verifyCompanionScreenshot(filePath, failures)
    const metadata = await readMetadata(filePath, failures)
    if (!metadata) continue

    if (
      metadata.sdk?.name !== '@argos-ci/playwright' ||
      metadata.automationLibrary?.name !== '@playwright/test'
    ) {
      continue
    }

    failures.push(...validatePlaywrightMetadata(metadata, filePath, config))
    if (Array.isArray(metadata.test?.titlePath)) {
      uniqueTests.add(metadata.test.titlePath.join(' > '))
    }
    if (Array.isArray(metadata.tags)) {
      for (const { tag } of config.requiredDomainCounts) {
        if (metadata.tags.includes(tag)) {
          domainCounts.set(tag, (domainCounts.get(tag) || 0) + 1)
        }
      }
    }
  }

  if (metadataFiles.length < config.expectedMetadata) {
    failures.push(`expected at least ${config.expectedMetadata} Argos screenshot metadata files, found ${metadataFiles.length}`)
  }
  if (uniqueTests.size < config.expectedTests) {
    failures.push(`expected at least ${config.expectedTests} unique Argos-backed Playwright tests, found ${uniqueTests.size}`)
  }
  for (const { tag, count } of config.requiredDomainCounts) {
    const actual = domainCounts.get(tag) || 0
    if (actual < count) {
      failures.push(`expected at least ${count} Argos screenshot metadata files tagged ${tag}, found ${actual}`)
    }
  }

  return {
    failures,
    summary: `verified ${metadataFiles.length} screenshot metadata files across ${uniqueTests.size} Playwright tests`,
  }
}

async function verifyStorybook(config) {
  const metadataFiles = await collectMetadataFiles(config.root)
  const failures = []
  const uniqueStories = new Set()
  const uniqueStoriesWithTestMetadata = new Set()
  const domainStories = new Map()

  for (const filePath of metadataFiles) {
    await verifyCompanionScreenshot(filePath, failures)
    const metadata = await readMetadata(filePath, failures)
    if (!metadata) continue

    if (
      metadata.sdk?.name !== '@argos-ci/storybook' ||
      metadata.automationLibrary?.name !== '@storybook/addon-vitest'
    ) {
      continue
    }

    failures.push(...validateStorybookMetadata(metadata, filePath, config))
    if (typeof metadata.story?.id === 'string') {
      uniqueStories.add(metadata.story.id)
      if (Array.isArray(metadata.story?.tags)) {
        for (const { tag } of config.requiredDomainStoryCounts) {
          if (metadata.story.tags.includes(tag)) {
            const stories = domainStories.get(tag) || new Set()
            stories.add(metadata.story.id)
            domainStories.set(tag, stories)
          }
        }
      }
    }
    if (
      typeof metadata.story?.id === 'string' &&
      typeof metadata.test?.title === 'string' &&
      Array.isArray(metadata.test?.titlePath) &&
      typeof metadata.test?.location?.file === 'string'
    ) {
      uniqueStoriesWithTestMetadata.add(metadata.story.id)
    }
  }

  if (metadataFiles.length < config.expectedMetadata) {
    failures.push(`expected at least ${config.expectedMetadata} Argos Storybook metadata files, found ${metadataFiles.length}`)
  }
  if (uniqueStories.size < config.expectedStories) {
    failures.push(`expected at least ${config.expectedStories} unique Argos-backed Storybook stories, found ${uniqueStories.size}`)
  }
  if (uniqueStoriesWithTestMetadata.size < config.expectedStories) {
    failures.push(`expected at least ${config.expectedStories} Storybook stories with test/source metadata, found ${uniqueStoriesWithTestMetadata.size}`)
  }
  for (const { tag, count } of config.requiredDomainStoryCounts) {
    const actual = domainStories.get(tag)?.size || 0
    if (actual < count) {
      failures.push(`expected at least ${count} Argos-backed Storybook stories tagged ${tag}, found ${actual}`)
    }
  }

  return {
    failures,
    summary: `verified ${metadataFiles.length} screenshot metadata files across ${uniqueStories.size} Storybook stories; ${uniqueStoriesWithTestMetadata.size} stories include test/source metadata`,
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  const config = args.mode === 'playwright'
    ? getPlaywrightConfig(args.root)
    : getStorybookConfig(args.root)

  if (!await pathExists(config.root)) {
    console.error(`[${config.label}] ${config.root} does not exist`)
    process.exit(1)
  }

  const result = args.mode === 'playwright'
    ? await verifyPlaywright(config)
    : await verifyStorybook(config)

  if (result.failures.length > 0) {
    console.error(`[${config.label}] Argos metadata verification failed:`)
    for (const failure of result.failures) {
      console.error(`- ${failure}`)
    }
    process.exit(1)
  }

  console.log(`[${config.label}] ${result.summary}`)
}

main().catch((error) => {
  console.error(`[argos-metadata] ${error.stack || error.message}`)
  process.exit(1)
})
