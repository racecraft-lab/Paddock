#!/usr/bin/env node

import { access, readdir, readFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.argv[2] || path.join(process.cwd(), 'screenshots')
const expectedMetadata = Number.parseInt(process.env.SPEC002_ARGOS_STORYBOOK_EXPECTED_METADATA || '16', 10)
const expectedStories = Number.parseInt(process.env.SPEC002_ARGOS_STORYBOOK_EXPECTED_STORIES || '8', 10)
const requiredStoryTags = (process.env.SPEC002_ARGOS_STORYBOOK_REQUIRED_TAGS || 'spec-002,visual')
  .split(',')
  .map((tag) => tag.trim())
  .filter(Boolean)

async function pathExists(filePath) {
  try {
    await access(filePath)
    return true
  } catch {
    return false
  }
}

async function collectMetadataFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...await collectMetadataFiles(entryPath))
      continue
    }
    if (entry.isFile() && entry.name.endsWith('.png.argos.json')) {
      files.push(entryPath)
    }
  }

  return files
}

function validateMetadata(metadata, filePath) {
  const failures = []

  if (metadata.sdk?.name !== '@argos-ci/storybook') {
    failures.push('metadata was not generated by @argos-ci/storybook')
  }
  if (metadata.automationLibrary?.name !== '@storybook/addon-vitest') {
    failures.push('metadata was not generated from @storybook/addon-vitest')
  }
  if (typeof metadata.story?.id !== 'string' || !metadata.story.id.startsWith('spec-002-')) {
    failures.push('missing SPEC-002 story id')
  }
  for (const tag of requiredStoryTags) {
    if (!Array.isArray(metadata.story?.tags) || !metadata.story.tags.includes(tag)) {
      failures.push(`missing Storybook story tag ${tag}`)
    }
  }

  return failures.map((failure) => `${path.relative(process.cwd(), filePath)}: ${failure}`)
}

if (!await pathExists(root)) {
  console.error(`[argos-storybook-metadata] ${root} does not exist`)
  process.exit(1)
}

const metadataFiles = await collectMetadataFiles(root)
const failures = []
const uniqueStories = new Set()
const uniqueStoriesWithTestMetadata = new Set()

for (const filePath of metadataFiles) {
  const screenshotPath = filePath.slice(0, -'.argos.json'.length)
  if (!await pathExists(screenshotPath)) {
    failures.push(`${path.relative(process.cwd(), filePath)}: missing companion screenshot`)
  }

  let metadata
  try {
    metadata = JSON.parse(await readFile(filePath, 'utf8'))
  } catch (error) {
    failures.push(`${path.relative(process.cwd(), filePath)}: invalid JSON (${error.message})`)
    continue
  }

  failures.push(...validateMetadata(metadata, filePath))
  if (typeof metadata.story?.id === 'string') {
    uniqueStories.add(metadata.story.id)
  }
  if (
    typeof metadata.story?.id === 'string'
    && typeof metadata.test?.title === 'string'
    && Array.isArray(metadata.test?.titlePath)
    && typeof metadata.test?.location?.file === 'string'
  ) {
    uniqueStoriesWithTestMetadata.add(metadata.story.id)
  }
}

if (metadataFiles.length < expectedMetadata) {
  failures.push(`expected at least ${expectedMetadata} Argos Storybook metadata files, found ${metadataFiles.length}`)
}
if (uniqueStories.size < expectedStories) {
  failures.push(`expected at least ${expectedStories} unique Argos-backed Storybook stories, found ${uniqueStories.size}`)
}
if (uniqueStoriesWithTestMetadata.size < expectedStories) {
  failures.push(`expected at least ${expectedStories} Storybook stories with test/source metadata, found ${uniqueStoriesWithTestMetadata.size}`)
}

if (failures.length > 0) {
  console.error('[argos-storybook-metadata] Argos Storybook metadata verification failed:')
  for (const failure of failures) {
    console.error(`- ${failure}`)
  }
  process.exit(1)
}

console.log(`[argos-storybook-metadata] verified ${metadataFiles.length} screenshot metadata files across ${uniqueStories.size} Storybook stories; ${uniqueStoriesWithTestMetadata.size} stories include test/source metadata`)
