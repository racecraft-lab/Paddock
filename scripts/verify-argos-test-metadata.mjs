#!/usr/bin/env node

import { access, readdir, readFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.argv[2] || path.join(process.cwd(), 'test-results')
const expectedMetadata = Number.parseInt(process.env.SPEC002_ARGOS_EXPECTED_METADATA || '9', 10)
const expectedTests = Number.parseInt(process.env.SPEC002_ARGOS_EXPECTED_TESTS || '4', 10)
const requiredTestTag = process.env.SPEC002_ARGOS_REQUIRED_TEST_TAG || '@spec-002'
const requiredScreenshotTags = (process.env.SPEC002_ARGOS_REQUIRED_SCREENSHOT_TAGS || 'spec-002,product-line-switcher')
  .split(',')
  .map((tag) => tag.trim())
  .filter(Boolean)

async function pathExists(filePath) {
  try {
    await access(filePath)
    return true
  } catch {
    return false
  }
}

async function collectMetadataFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...await collectMetadataFiles(entryPath))
      continue
    }
    if (entry.isFile() && entry.name.endsWith('.png.argos.json')) {
      files.push(entryPath)
    }
  }

  return files
}

function validateMetadata(metadata, filePath) {
  const failures = []
  const test = metadata.test

  if (!test || typeof test !== 'object') {
    failures.push('missing test metadata')
    return failures
  }
  if (typeof test.title !== 'string' || test.title.length === 0) {
    failures.push('missing test.title')
  }
  if (!Array.isArray(test.titlePath) || test.titlePath.length === 0) {
    failures.push('missing test.titlePath')
  }
  if (typeof test.location?.file !== 'string' || test.location.file.length === 0) {
    failures.push('missing test.location.file')
  }
  if (!Array.isArray(test.tags) || !test.tags.includes(requiredTestTag)) {
    failures.push(`missing Playwright test tag ${requiredTestTag}`)
  }
  for (const tag of requiredScreenshotTags) {
    if (!Array.isArray(metadata.tags) || !metadata.tags.includes(tag)) {
      failures.push(`missing screenshot tag ${tag}`)
    }
  }
  if (metadata.sdk?.name !== '@argos-ci/playwright') {
    failures.push('metadata was not generated by @argos-ci/playwright')
  }
  if (metadata.automationLibrary?.name !== '@playwright/test') {
    failures.push('metadata was not generated from @playwright/test')
  }

  if (failures.length > 0) {
    return failures.map((failure) => `${path.relative(process.cwd(), filePath)}: ${failure}`)
  }
  return failures
}

if (!await pathExists(root)) {
  console.error(`[argos-metadata] ${root} does not exist`)
  process.exit(1)
}

const metadataFiles = await collectMetadataFiles(root)
const failures = []
const uniqueTests = new Set()

for (const filePath of metadataFiles) {
  const screenshotPath = filePath.slice(0, -'.argos.json'.length)
  if (!await pathExists(screenshotPath)) {
    failures.push(`${path.relative(process.cwd(), filePath)}: missing companion screenshot`)
  }

  let metadata
  try {
    metadata = JSON.parse(await readFile(filePath, 'utf8'))
  } catch (error) {
    failures.push(`${path.relative(process.cwd(), filePath)}: invalid JSON (${error.message})`)
    continue
  }

  failures.push(...validateMetadata(metadata, filePath))
  if (Array.isArray(metadata.test?.titlePath)) {
    uniqueTests.add(metadata.test.titlePath.join(' > '))
  }
}

if (metadataFiles.length < expectedMetadata) {
  failures.push(`expected at least ${expectedMetadata} Argos screenshot metadata files, found ${metadataFiles.length}`)
}
if (uniqueTests.size < expectedTests) {
  failures.push(`expected at least ${expectedTests} unique Argos-backed Playwright tests, found ${uniqueTests.size}`)
}

if (failures.length > 0) {
  console.error('[argos-metadata] Argos test metadata verification failed:')
  for (const failure of failures) {
    console.error(`- ${failure}`)
  }
  process.exit(1)
}

console.log(`[argos-metadata] verified ${metadataFiles.length} screenshot metadata files across ${uniqueTests.size} Playwright tests`)
